/** Fills Android-style placeholders: %1$s, %2$d, … and %% (a literal %). */
export function fmt(template: string, ...args: (string | number)[]): string {
  return template
    .replace(/%(\d+)\$[sd]/g, (_, n: string) => String(args[Number(n) - 1] ?? ""))
    .replace(/%%/g, "%")
}

